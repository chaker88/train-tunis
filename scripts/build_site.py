"""Write the site address (data/site.json -> SITE_URL) into the files that need it as plain text.

- public/index.html: the search/social tags and the JSON-LD block between the "site-meta" markers,
  plus the JSON-LD sha256 hash in the Content-Security-Policy <meta> tag;
- public/_headers: the same hash in the Content-Security-Policy header;
- public/robots.txt and public/sitemap.xml.

Run by build_data.py (and so by start.bat). Running it twice changes nothing.
"""
import base64
import hashlib
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE_FILE = ROOT / "data" / "site.json"
PUBLIC = ROOT / "public"

AUTHOR = "Chaker Saidi"
AUTHOR_LINKS = ["https://www.linkedin.com/in/chaker-saidi"]
TITLE = "القطار القادم — قطارات ضواحي تونس"
NAME_EN = "Next Train — Tunis suburban trains"
DESCRIPTION = (
    "القطار القادم: اعرف مواعيد القطارات الثلاثة القادمة على خطوط ضواحي تونس A وD وE، "
    "مع العدّ التنازلي وتوقيت الآحاد والأعياد ورمضان. تطبيق مجاني وغير رسمي، بالعربية والإنجليزية."
)
DESCRIPTION_EN = (
    "Next Train: the next 3 departures on Tunis suburban lines A, D and E, with a live countdown, "
    "Sunday, holiday and Ramadan timetables. Free, unofficial, in Arabic and English."
)
OG_IMAGE = "assets/og-image.png"
OG_IMAGE_ALT = "القطار القادم — Next Train: خطوط ضواحي تونس A وD وE"

START = "<!-- site-meta:start (generated by scripts/build_site.py from data/site.json, do not edit by hand) -->"
END = "<!-- site-meta:end -->"
BLOCK_RE = re.compile(r"<!-- site-meta:start[^>]*-->.*?<!-- site-meta:end -->", re.S)
LD_RE = re.compile(r'<script type="application/ld\+json">(.*?)</script>', re.S)
CSP_SCRIPT_RE = re.compile(r"script-src 'self'(?: 'sha256-[A-Za-z0-9+/=]+')*")


class SiteError(Exception):
    pass


def load_site_url(site_file=SITE_FILE):
    try:
        url = json.loads(site_file.read_text(encoding="utf-8"))["SITE_URL"]
    except (OSError, ValueError, KeyError, TypeError) as e:
        raise SiteError(f"{site_file.name}: cannot read SITE_URL ({e}).")
    if not isinstance(url, str) or not re.fullmatch(r"https://[a-z0-9.-]+(?::\d+)?(?:/[\w./-]*)?", url, re.I):
        raise SiteError(f'{site_file.name}: SITE_URL must look like "https://my-site.pages.dev" (found {url!r}).')
    return url.rstrip("/")


def json_ld(site_url):
    data = {
        "@context": "https://schema.org",
        "@type": "WebApplication",
        "name": TITLE,
        "alternateName": NAME_EN,
        "url": f"{site_url}/",
        "image": f"{site_url}/{OG_IMAGE}",
        "description": DESCRIPTION_EN,
        "applicationCategory": "TravelApplication",
        "operatingSystem": "Any",
        "browserRequirements": "Requires JavaScript",
        "isAccessibleForFree": True,
        "inLanguage": ["ar", "en"],
        "offers": {"@type": "Offer", "price": "0", "priceCurrency": "TND"},
        "author": {"@type": "Person", "name": AUTHOR, "sameAs": AUTHOR_LINKS},
    }
    # One line, so Git's line-ending conversion can never change the bytes (and so the CSP hash).
    text = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    return text.replace("</", "<\\/")


def csp_hash(script_text):
    return "sha256-" + base64.b64encode(hashlib.sha256(script_text.encode("utf-8")).digest()).decode()


def meta_block(site_url, nl):
    a = lambda s: html.escape(s, quote=True)
    url, image = f"{site_url}/", f"{site_url}/{OG_IMAGE}"
    tags = [
        START,
        f'<meta name="description" content="{a(DESCRIPTION)}">',
        f'<meta name="author" content="{a(AUTHOR)}">',
        f'<link rel="canonical" href="{a(url)}">',
        '<meta property="og:type" content="website">',
        f'<meta property="og:site_name" content="{a(TITLE)}">',
        f'<meta property="og:title" content="{a(TITLE)}">',
        f'<meta property="og:description" content="{a(DESCRIPTION)}">',
        f'<meta property="og:url" content="{a(url)}">',
        f'<meta property="og:image" content="{a(image)}">',
        '<meta property="og:image:type" content="image/png">',
        '<meta property="og:image:width" content="1200">',
        '<meta property="og:image:height" content="630">',
        f'<meta property="og:image:alt" content="{a(OG_IMAGE_ALT)}">',
        '<meta property="og:locale" content="ar_TN">',
        '<meta property="og:locale:alternate" content="en_US">',
        '<meta name="twitter:card" content="summary_large_image">',
        f'<meta name="twitter:title" content="{a(TITLE)}">',
        f'<meta name="twitter:description" content="{a(DESCRIPTION)}">',
        f'<meta name="twitter:image" content="{a(image)}">',
        f'<meta name="twitter:image:alt" content="{a(OG_IMAGE_ALT)}">',
        f'<script type="application/ld+json">{json_ld(site_url)}</script>',
        END,
    ]
    return (nl + "  ").join(tags)


def read(path):
    # newline="" keeps the file's own line endings (CRLF on Windows checkouts).
    with path.open(encoding="utf-8", newline="") as f:
        return f.read()


def write_if_changed(path, text):
    if path.exists() and read(path) == text:
        return False
    with path.open("w", encoding="utf-8", newline="") as f:
        f.write(text)
    return True


def set_csp_hash(text, digest, where):
    new, n = CSP_SCRIPT_RE.subn(f"script-src 'self' '{digest}'", text)
    if n != 1:
        raise SiteError(f"{where}: expected exactly one Content-Security-Policy script-src, found {n}.")
    return new


def build_site(public=PUBLIC, site_file=SITE_FILE):
    site_url = load_site_url(site_file)
    changed = []

    index = public / "index.html"
    text = read(index)
    nl = "\r\n" if "\r\n" in text else "\n"
    if not BLOCK_RE.search(text):
        raise SiteError(f"{index.name}: the site-meta markers are missing from <head>.")
    text = BLOCK_RE.sub(lambda _: meta_block(site_url, nl), text, count=1)
    digest = csp_hash(LD_RE.search(text).group(1))
    text = set_csp_hash(text, digest, index.name)
    if write_if_changed(index, text):
        changed.append(index)

    headers = public / "_headers"
    if write_if_changed(headers, set_csp_hash(read(headers), digest, headers.name)):
        changed.append(headers)

    robots = f"User-agent: *\nAllow: /\n\nSitemap: {site_url}/sitemap.xml\n"
    sitemap = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        f"  <url>\n    <loc>{html.escape(site_url)}/</loc>\n  </url>\n"
        "</urlset>\n"
    )
    for name, content in (("robots.txt", robots), ("sitemap.xml", sitemap)):
        if write_if_changed(public / name, content):
            changed.append(public / name)
    return site_url, changed


def main():
    try:
        site_url, changed = build_site()
    except SiteError as e:
        print(f"\nSITE SETUP FAILED\n{e}\n", file=sys.stderr)
        sys.exit(1)
    print(f"Site address: {site_url}" + (f" (updated {', '.join(p.name for p in changed)})" if changed else ""))
    if "REPLACE-ME" in site_url:
        print('  reminder: set your real address in data/site.json ("SITE_URL") before publishing.')


if __name__ == "__main__":
    main()
